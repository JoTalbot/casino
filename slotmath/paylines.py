"""
Определения выигрышных линий для сетки 5 барабанов x 3 ряда.

Каждая линия — список из 5 номеров рядов (0 = верхний, 1 = средний, 2 = нижний).
Индекс в списке = номер барабана.

Все линии оцениваются слева направо, начиная с первого барабана —
это классическое правило, оно же самое простое для сертификации.
"""

from typing import List

# 20 фиксированных линий. Порядок соответствует нумерации в интерфейсе (Line 1..20).
PAYLINES: List[List[int]] = [
    [1, 1, 1, 1, 1],  # 1  — центральная
    [0, 0, 0, 0, 0],  # 2  — верхняя
    [2, 2, 2, 2, 2],  # 3  — нижняя
    [0, 1, 2, 1, 0],  # 4  — V
    [2, 1, 0, 1, 2],  # 5  — Λ
    [0, 0, 1, 2, 2],  # 6
    [2, 2, 1, 0, 0],  # 7
    [1, 2, 2, 2, 1],  # 8
    [1, 0, 0, 0, 1],  # 9
    [1, 0, 1, 2, 1],  # 10
    [1, 2, 1, 0, 1],  # 11
    [0, 1, 1, 1, 0],  # 12
    [2, 1, 1, 1, 2],  # 13
    [0, 1, 0, 1, 0],  # 14 — зигзаг сверху
    [2, 1, 2, 1, 2],  # 15 — зигзаг снизу
    [1, 1, 0, 1, 1],  # 16
    [1, 1, 2, 1, 1],  # 17
    [0, 2, 0, 2, 0],  # 18
    [2, 0, 2, 0, 2],  # 19
    [0, 2, 2, 2, 0],  # 20
]

NUM_LINES = len(PAYLINES)
NUM_REELS = 5
NUM_ROWS = 3


def validate_paylines() -> None:
    """Проверяет корректность определений линий. Вызывается в тестах."""
    seen = set()
    for idx, line in enumerate(PAYLINES, start=1):
        if len(line) != NUM_REELS:
            raise ValueError(f"Линия {idx}: ожидалось {NUM_REELS} позиций, получено {len(line)}")
        for row in line:
            if not 0 <= row < NUM_ROWS:
                raise ValueError(f"Линия {idx}: ряд {row} вне диапазона 0..{NUM_ROWS - 1}")
        key = tuple(line)
        if key in seen:
            raise ValueError(f"Линия {idx}: дубликат {key}")
        seen.add(key)
