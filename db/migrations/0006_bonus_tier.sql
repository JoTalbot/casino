-- =============================================================================
-- Бонус-игра «Сундуки короны»: тир, выбранный игроком до спина (T-195)
--
-- Тир нужен для повторной проверки раунда: при разных тирах одна и та же
-- пара сидов даёт разную серию фриспинов, и без этого поля сторонний
-- верификатор не воспроизведёт результат.
-- =============================================================================

BEGIN;

ALTER TABLE rounds ADD COLUMN IF NOT EXISTS bonus_tier SMALLINT NOT NULL DEFAULT 1;

COMMENT ON COLUMN rounds.bonus_tier IS
    'Тир бонус-игры (1 — обычная серия фриспинов). Участвует в проверке раунда.';

COMMIT;
